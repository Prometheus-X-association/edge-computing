import typing

from pydantic import BaseModel, HttpUrl, Field

from app.model.ptxedgeworker import PEW
from app.model.responses import PTXEdgeWorkerResponse


class PTXServiceChainInfraRequest(BaseModel):
    contract: typing.Annotated[HttpUrl, Field(description="Dataspace contract URL", min_length=1)]
    data: typing.Annotated[list[PEW], Field(description="Worker configurations")]
    params: typing.Annotated[dict[str, typing.Any], Field(description="Infra key-value parameters")] = None
    previousNodeParams: typing.Annotated[
        str | dict[str, typing.Any], Field(description="Previous node parameters")] = None


class PTXServiceChainInfraResponse(BaseModel):
    contract: typing.Annotated[HttpUrl, Field(description="Dataspace contract URL", min_length=1)]
    data: typing.Annotated[list[PTXEdgeWorkerResponse], Field(description="Worker states")]
    params: typing.Annotated[str | dict[str, typing.Any], Field(description="Infra key-value parameters")] = None


class PTXServiceChainInfraHeaders(BaseModel):
    x_ptx_service_chain_id: typing.Annotated[
        str | None, Field(description="ID generated by the Data Processing Chain library")] = None
    # x_ptx_service_chain_previous_target: typing.Annotated[
    #     str | None, Field(description="Previous resource in the service chain")] = None
    # x_ptx_service_chain_next_target: typing.Annotated[
    #     str | None, Field(description="Next resource in the service chain")] = None
    x_ptx_target_id: typing.Annotated[
        str | None, Field(description="Current resource being processed")] = None
    # x_ptx_incomingdataspaceconnectoruri: typing.Annotated[
    #     str | None, Field(description="First node's connector URI")] = None
    # x_ptx_dataexchangeid: typing.Annotated[
    #     str | None, Field(description="Data exchange ID relative to the active participant")] = None
    # x_ptx_contractid: typing.Annotated[
    #     str | None, Field(description="ID of the current contract being used")] = None
    x_ptx_contracturl: typing.Annotated[
        str | None, Field(description="Full URL with the ID of the current contract being used")] = None


class PTXServiceChainResumeCallback(BaseModel):
    chainId: typing.Annotated[str, Field(description="Service chain ID")]
    targetId: typing.Annotated[str, Field(description="Current resource being processed")]
    data: typing.Annotated[list[PTXEdgeWorkerResponse], Field(description="Worker states")]
    params: typing.Annotated[dict[str, typing.Any], Field(description="Infra key-value parameters")] = None
