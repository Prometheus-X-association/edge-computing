PTX_CONSENT_URI="https://consent.visionstrust.com/v1"           # optional (live)

IMAGES=("${BUILD_IMG}" "${CONTROL_IMG}" "${PDC_IMG}" "${MONGODB_IMG}" "${API_IMG}" "${SCHED_IMG}" "${CATALOG_IMG}")

# Applied PDC configuration
if [ "${USE_SANDBOX}" = "true" ]; then
    USED_PDC_CONFIG="sandbox-cfg.json"
else
    USED_PDC_CONFIG="dataspace-cfg.json"
fi

########################################################################################################################

# Global ptx-edge config
PREFIX="${PTX}/api/v1"
BUILD_TIMEOUT=600

