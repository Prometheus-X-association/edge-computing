set -o allexport    # Also export all defined variables for 'envsubst'

########################################################################################################################

# Define base path for absolute file access
SCRIPT_DIR=$(readlink -f "$(dirname "${BASH_SOURCE[0]}")/..")  # edge-server/
ROOT_DIR=$(readlink -f "${SCRIPT_DIR}/../..")   # kubernetes/

# Import essentials as logging, etc.
source "${SCRIPT_DIR}/cfg/helper.sh"

# Set colorful logging if available
if command -v kubecolor >/dev/null 2>&1; then
    KUBECOLOR_FORCE_COLORS=auto
    KUBECOLOR_PRESET="dark"
    KCTL=kubecolor
else
    KCTL=kubectl
fi

# Import additional confidential configurations from creds folder
for cfg in "${SCRIPT_DIR}"/creds/*.sh; do
    source "${cfg}"
done

# Global settings of deployment configuration
# Default to false, can be override from creds/0-default-config.sh !
USE_SANDBOX="${USE_SANDBOX:-false}"
LOCAL_SETUP="${LOCAL_SETUP:-false}"
USE_NGROK="${USE_NGROK:-false}"

########################################################################################################################

# Fundamental cluster configuration
TIMEOUT=120
CLUSTER="edge-server"
ENV="demo"

# Registry
REGISTRY="registry.k3d.local"
REGISTRY_PORT=5000
# Loaded from creds/fured-cloud-creds.sh !
### REGISTRY_USER=
### REGISTRY_SECRET=
K3D_REG="registry.k3d.localhost:${REGISTRY_PORT}"
REG_CREDS="${REGISTRY_USER}:${REGISTRY_SECRET}"
CA_DIR="${SCRIPT_DIR}/creds/cert/ca"

# Loadbalancer
LB_WEB_PORT=8080
LB_WEBSECURE_PORT=8443
LB_DOMAIN="${CLUSTER}.k3d.localhost"
CLUSTER_HOST="${LB_DOMAIN}:${LB_WEBSECURE_PORT}"
# Loaded from creds/fured-cloud-creds.sh !
### GW_DOMAIN=
### GW_PORT=
### USE_NGROK=
### NGROK_DOMAIN=
if [ "${USE_NGROK}" = "true" ] && [ -v NGROK_DOMAIN ] ; then
    GW_HOST="${NGROK_DOMAIN}"
else
    GW_HOST="${GW_DOMAIN}:${GW_PORT}"
fi

PRIMARY_IP="$(ip route get 1 | awk '{print $(NF-2);exit}')"
PRIMARY_HOST="${PRIMARY_IP}:${LB_WEBSECURE_PORT}"

CLUSTER_TLS_SECRET="cluster-websecure-tls"

########################################################################################################################

# PTX namespace
PTX="ptx-edge"

# Privacy zones
DEF_ZONE="default"

# PTX-edge components
COMPONENTS=(builder controller ptx registry rest-api scheduler)
#
BUILD_IMG="ptx-edge/builder:1.0"
CONTROL_IMG="ptx-edge/controller:1.0"
PDC_IMG="ptx/connector:1.11.0-slim"
MONGODB_IMG="ptx/mongodb:8.0.23-slim"
API_IMG="ptx-edge/rest-api:1.0"
SCHED_IMG="ptx-edge/scheduler:1.0"

# PTX-sandbox components
CATALOG_IMG="ptx-sandbox/catalog:1.11.0-slim"
SANDBOX="ptx-sandbox"
CATALOG="catalog"
CATALOG_DNS="${CATALOG}.${SANDBOX}.svc.cluster.local"

# API auth
# Loaded from creds/fured-cloud-creds.sh !
### API_BASIC_USER=
### API_BASIC_PASSWORD=
API_CREDS=$(htpasswd -Bnb "${API_BASIC_USER}" "${API_BASIC_PASSWORD}")
API_CREDS_BASE64_ENCODED=$(printf '%s' "${API_CREDS}" | openssl base64 -A)

# PDC
PDC=pdc
PDC_ENV=development
PDC_PORT=3000
PDC_ID='${PDC_ID}'          # placeholder for keeping PDC's service/ingress name
PDC_DEF_PZ='${PDC_DEF_PZ}'  # placeholder for keeping PDC's privacy zone ID
PDC_SECRET_NAME="${PDC}-secret-env"
# Loaded from creds/fured-cloud-creds.sh !
### PDC_SERVICE_KEY=
### PDC_SECRET_KEY=
PDC_CFG_SERVICE_KEY='${SERVICE_KEY}'  # placeholder for injecting key in runtime
PDC_CFG_SECRET_KEY='${SECRET_KEY}'  # placeholder for injecting key in runtime
PDC_CFG_EXCHANGE_TRIGGER_API_KEY='${EXCHANGE_TRIGGER_API_KEY}'  # placeholder for injecting key in runtime
#
PDC_SERVICE_KEY_BASE64_ENCODED=$(printf '%s' "${PDC_SERVICE_KEY}" | base64 -w0)
PDC_SECRET_KEY_BASE64_ENCODED=$(printf '%s' "${PDC_SECRET_KEY}" | base64 -w0)
PDC_EXCHANGE_TRIGGER_API_KEY_BASE64_ENCODED=$(printf '%s' "${PDC_EXCHANGE_TRIGGER_API_KEY}" | base64 -w0)
PDC_SESSION_SECRET=$(openssl rand -base64 32 | tr -d /=+ | cut -c -16)    # Autogenerated
#
PDC_CFG_ENDPOINT="https://${GW_HOST}/${PTX}/${PDC_DEF_PZ}/${PDC}"
#
#
#### MONGO_DB_NAME=
#### MONGO_DB_USER=
#### MONGO_DB_PASSWORD=
MONGO_CFG_DB_NAME='${MONGO_DB_NAME}'     # placeholder for injecting key in runtime
MONGO_CFG_DB_USER='${MONGO_DB_USER}'     # placeholder for injecting key in runtime
MONGO_CFG_DB_PASSWORD='${MONGO_DB_PASSWORD}'     # placeholder for injecting key in runtime
